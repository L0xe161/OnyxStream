/**
 * Subtitle utilities: SRT → WebVTT conversion and Arabic Windows-1256 decoding.
 * Used by the SubDL subtitle proxy.
 */

/**
 * Decode a raw subtitle buffer to a string.
 * Strategy:
 *  1. If UTF-8 BOM present → strip and decode UTF-8.
 *  2. Try strict UTF-8 (fatal) — if it passes, use it.
 *  3. Fall back to Windows-1256 (standard Arabic subtitle encoding).
 *  4. Last resort: permissive UTF-8.
 */
export function decodeSubtitleBuffer(buffer: Buffer): string {
  // UTF-8 BOM
  if (buffer.length >= 3 && buffer[0] === 0xef && buffer[1] === 0xbb && buffer[2] === 0xbf) {
    return buffer.subarray(3).toString("utf-8");
  }

  // Strict UTF-8 attempt
  try {
    const utf8Decoder = new TextDecoder("utf-8", { fatal: true });
    return utf8Decoder.decode(buffer);
  } catch {
    // Fall through to Windows-1256
  }

  // Windows-1256 (Arabic) software decode — no external dependency.
  return decodeWin1256(buffer);
}

