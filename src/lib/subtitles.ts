export function decodeWin1256(buffer: Buffer): string {
  let out = "";
  for (let i = 0; i < buffer.length; i++) {
    const byte = buffer[i];
    if (byte < 0x80) {
      out += String.fromCharCode(byte);
    } else {
      const code = WIN1256_MAP[byte];
      out += String.fromCharCode(code ?? 0xfffd);
    }
  }
  return out;
}

/**
 * Convert a raw SRT string to standard WebVTT format.
 * - Strips BOM, normalises line endings.
 * - Converts SRT timecodes (00:01:20,000) to WebVTT (00:01:20.000).
 */
export function convertSrtToVtt(srtContent: string): string {
  if (!srtContent || typeof srtContent !== "string") {
    return "WEBVTT\n\n";
  }

  const normalized = srtContent
    .replace(/^\uFEFF/, "")
    .replace(/\r\n/g, "\n")
    .replace(/\r/g, "\n")
    .trim();

  // SRT timecode: 00:01:20,000 --> 00:01:23,456  →  WebVTT: 00:01:20.000 --> 00:01:23.456
  const convertedTimecodes = normalized.replace(
    /(\d{2}:\d{2}:\d{2}),(\d{3})/g,
    "$1.$2"
  );

  // If the file is already a VTT, ensure header exists.
  if (/^WEBVTT/i.test(convertedTimecodes)) {
    return convertedTimecodes;
  }
  return `WEBVTT\n\n${convertedTimecodes}\n`;
}

/** Build a minimal valid WebVTT cue (used for fallbacks). */
export function buildFallbackVtt(message: string, durationSec = 6): string {
  return `WEBVTT\n\n00:00:01.000 --> 00:00:${String(durationSec).padStart(2, "0")}.000\n${message}\n`;
}
